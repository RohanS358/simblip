#!/usr/bin/env node
// Writes docs/steplab-engines.md from the engine registry, so the list of engines,
// their parameters and what each one is for can never drift from the code.
//   node scripts/build-engine-docs.mjs
import { writeFileSync, mkdtempSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const root = resolve(import.meta.dirname, '..')
const tmp = mkdtempSync(join(tmpdir(), 'eng-'))
execFileSync('npx', ['esbuild', join(root, 'lib/steplab/registry.ts'), '--bundle', '--format=esm', `--outfile=${tmp}/r.mjs`, `--alias:@=${root}`], { cwd: root, stdio: 'pipe' })
const { ENGINES, runEngine } = await import(pathToFileURL(`${tmp}/r.mjs`).href)

const groups = new Map()
for (const e of ENGINES) groups.set(e.group, [...(groups.get(e.group) ?? []), e])
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ')
const out = [
  '# Step Lab engines', '',
  `Generated by \`node scripts/build-engine-docs.mjs\` from \`lib/steplab/engines/*\` — ${ENGINES.length} engines. Edit the engine, not this file. How the system works: [steplab.md](steplab.md).`, '',
]
for (const [g, list] of groups) {
  out.push(`## ${g}`, '')
  for (const e of list) {
    const r = runEngine({ engine: e.id })
    const keys = r.ok ? Object.keys(r.trace.summary) : []
    out.push(`### \`${e.id}\` — ${e.label}`, '', e.blurb, '',
      '| Parameter | Meaning | Default |', '|---|---|---|',
      ...e.params.map((p) => `| \`${p.name}\` | ${cell(p.label)}${p.hint ? ` — ${cell(p.hint)}` : ''}${p.options ? ` (${p.options.join(' / ')})` : ''} | ${p.def === '' ? '*(empty)*' : '`' + cell(p.def).replace(/`/g, '') + '`'} |`), '',
      keys.length ? `Results a lesson can pin with \`expect\`: ${keys.map((k) => `\`${k}\``).join(', ')}.` : '', '')
  }
}
writeFileSync(join(root, 'docs/steplab-engines.md'), out.join('\n') + '\n')
console.log(`docs/steplab-engines.md: ${ENGINES.length} engines in ${groups.size} groups`)
