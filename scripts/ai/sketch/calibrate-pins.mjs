// Measure where each class's pins fall as fractions of the drawn symbol's
// bounding box, by sampling real glyph output (leads intact), and write the
// table lib/sketch/pins.ts holds.
//
//   node --experimental-strip-types --import ./scripts/test/register.mjs scripts/ai/sketch/calibrate-pins.mjs [--write]
//
// A wire is matched to a pin by distance from these fractions, so they must
// describe the glyphs as drawn. pins.test.mjs fails if the table drifts from
// this measurement.

import { writeFileSync } from 'node:fs'
import { GLYPHS, PIN_FRAME } from '../../../lib/sketch/glyphs.ts'
import { makeRng } from '../../../lib/sketch/rng.ts'
import { WAVE1_CLASSES } from '../../../lib/sketch/classes.ts'

// A pin can sit a hair outside the box (mosfet drain at 1.008): it is ON the edge.
const clamp = (x) => +Math.min(1, Math.max(0, x)).toFixed(3)

export function measure() {
  const out = {}
  for (const cls of WAVE1_CLASSES) {
    const acc = PIN_FRAME[cls].map(() => [0, 0])
    const N = 60
    for (let i = 0; i < N; i++) {
      const g = GLYPHS[cls](makeRng(9000 + i))
      const pts = g.strokes.flatMap((s) => s.pts)
      const x0 = Math.min(...pts.map((p) => p[0])), x1 = Math.max(...pts.map((p) => p[0]))
      const y0 = Math.min(...pts.map((p) => p[1])), y1 = Math.max(...pts.map((p) => p[1]))
      PIN_FRAME[cls].forEach((pin, k) => {
        acc[k][0] += (pin.x - x0) / Math.max(x1 - x0, 1e-6)
        acc[k][1] += (pin.y - y0) / Math.max(y1 - y0, 1e-6)
      })
    }
    out[cls] = PIN_FRAME[cls].map((pin, k) => ({ name: pin.name, u: clamp(acc[k][0] / N), v: clamp(acc[k][1] / N) }))
  }
  return out
}

const table = measure()
const rows = WAVE1_CLASSES.map(
  (c) => `  '${c}': [${table[c].map((p) => `{ name: '${p.name}', u: ${p.u}, v: ${p.v} }`).join(', ')}],`
).join('\n')

const file = `// GENERATED by scripts/ai/sketch/calibrate-pins.mjs — do not edit by hand.
// Re-run it after changing PIN_FRAME or a glyph in glyphs.ts.
//
// Where each class's pins sit, as fractions (u across, v down) of the drawn
// symbol's bounding box at pose 0. A symbol drawn bare and one drawn with leads
// both put their end pins on the edges of their bounding box, so one table
// serves both. A wire end is matched to the nearest of these.

import type { Wave1Class, Pose } from './classes'

export interface PinTemplate {
  /** A SimScript anchor name. */
  name: string
  u: number
  v: number
}

export const PIN_TEMPLATE: Record<Wave1Class, PinTemplate[]> = {
${rows}
}

/** A pose-0 box fraction after turning the drawing by \`pose\` (clockwise, y down). */
export function rotateUV(u: number, v: number, pose: Pose): [number, number] {
  switch (pose) {
    case 90: return [1 - v, u]
    case 180: return [1 - u, 1 - v]
    case 270: return [v, 1 - u]
    default: return [u, v]
  }
}

export interface WorldPin {
  name: string
  x: number
  y: number
}

/** Pin positions (page px) for a recognised symbol drawn inside \`box\`. [] for classes with no template. */
export function pinsOf(cls: string, pose: Pose, box: { x0: number; y0: number; x1: number; y1: number }): WorldPin[] {
  const tpl = PIN_TEMPLATE[cls as Wave1Class]
  if (!tpl) return []
  const w = box.x1 - box.x0
  const h = box.y1 - box.y0
  return tpl.map((p) => {
    const [u, v] = rotateUV(p.u, p.v, pose)
    return { name: p.name, x: box.x0 + u * w, y: box.y0 + v * h }
  })
}
`

if (process.argv.includes('--write')) {
  writeFileSync('lib/sketch/pins.ts', file)
  console.log('wrote lib/sketch/pins.ts')
} else {
  console.log(file)
}
