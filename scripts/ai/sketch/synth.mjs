// Generate the SYNTHETIC sketch dataset.
//
//   npm run sketch:synth -- --seed 1 --writers 300 --reps 8
//
// Output (default data/sketch/synthetic/, git-ignored):
//   {train,val,test}-NNNN.jsonl.gz   one SketchSample per line (lib/sketch/dataset.ts)
//   MANIFEST.json                    options, counts, licence, per-shard sha256
//
// Everything written here has source "synthetic" or "synthetic-negative".
// Real collected data goes in its own directory with source "real" and is read
// by the same loader — see scripts/ai/sketch/dataset.mjs.

import { createHash } from 'node:crypto'
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { gzipSync } from 'node:zlib'
import { generate, GENERATOR_VERSION } from '../../../lib/sketch/synth.ts'
import { ALL_LABELS, CLASS_LIST_VERSION } from '../../../lib/sketch/classes.ts'

const arg = (name, dflt) => {
  const i = process.argv.indexOf(`--${name}`)
  return i > 0 ? process.argv[i + 1] : dflt
}
const seed = Number(arg('seed', 1))
const writers = Number(arg('writers', 300))
const reps = Number(arg('reps', 8))
const shardSize = Number(arg('shard-size', 4000))
const out = resolve(arg('out', 'data/sketch/synthetic'))

rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })

const buffers = { train: [], val: [], test: [] }
const shards = []
const counts = { split: { train: 0, val: 0, test: 0 }, cls: {}, device: {}, source: {} }
const writerSets = { train: new Set(), val: new Set(), test: new Set() }
const next = { train: 0, val: 0, test: 0 }

function flush(split) {
  const rows = buffers[split]
  if (!rows.length) return
  const file = `${split}-${String(next[split]++).padStart(4, '0')}.jsonl.gz`
  const bytes = gzipSync(Buffer.from(rows.join('\n') + '\n'), { level: 9 })
  writeFileSync(join(out, file), bytes)
  shards.push({ file, split, count: rows.length, sha256: createHash('sha256').update(bytes).digest('hex') })
  buffers[split] = []
}

const t0 = Date.now()
for (const s of generate({ seed, writers, reps })) {
  buffers[s.split].push(JSON.stringify(s))
  counts.split[s.split]++
  counts.cls[s.cls] = (counts.cls[s.cls] ?? 0) + 1
  counts.device[s.device] = (counts.device[s.device] ?? 0) + 1
  counts.source[s.source] = (counts.source[s.source] ?? 0) + 1
  writerSets[s.split].add(s.writer)
  if (buffers[s.split].length >= shardSize) flush(s.split)
}
for (const k of Object.keys(buffers)) flush(k)

const total = Object.values(counts.split).reduce((a, b) => a + b, 0)
const manifest = {
  name: `synthetic-s${seed}`,
  notice: 'SYNTHETIC. Generated hands, not people. Scores on this set must be reported as "synthetic" and never stand in for real-world validation.',
  source: ['synthetic', 'synthetic-negative'],
  licence: 'generated by SIMBLIP (no third-party data)',
  generatorVersion: GENERATOR_VERSION,
  classListVersion: CLASS_LIST_VERSION,
  labels: ALL_LABELS,
  options: { seed, writers, reps, unknownFactor: 2 },
  total,
  counts,
  writers: { train: writerSets.train.size, val: writerSets.val.size, test: writerSets.test.size },
  splitRule: 'by writer — no writer appears in more than one split',
  shards,
}
writeFileSync(join(out, 'MANIFEST.json'), JSON.stringify(manifest, null, 2) + '\n')
console.log(`wrote ${total} samples in ${shards.length} shards to ${out} (${((Date.now() - t0) / 1000).toFixed(1)}s)`)
console.log(`  splits  ${JSON.stringify(counts.split)}   writers ${JSON.stringify(manifest.writers)}`)
console.log(`  devices ${JSON.stringify(counts.device)}`)
